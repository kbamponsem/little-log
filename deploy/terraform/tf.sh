#!/usr/bin/env bash
#
# Run Terraform using the values in .env.
#
#   ./tf.sh plan
#   ./tf.sh apply
#
# Why this exists: Terraform cannot read a .env file, and a variable can only
# get its value from -var, a tfvars file, or a TF_VAR_* environment variable
# (variables cannot be computed). So this script translates .env into
# terraform.tfvars — which Terraform *does* auto-load — and then runs Terraform.
#
# You keep .env as the single place you edit. terraform.tfvars is generated
# (gitignored, chmod 600, because it holds the token).
#
# Plain `terraform apply` works too, as long as the tfvars file is current:
#   ./tf.sh            # sync only, no terraform command
#   terraform apply

set -euo pipefail
cd "$(dirname "$0")"

ENV_FILE=.env
TFVARS=terraform.tfvars

if [ ! -f "$ENV_FILE" ]; then
  echo "No $ENV_FILE in $(pwd)." >&2
  echo "Create it with your Proxmox details, e.g.:" >&2
  echo "  export PROXMOX_VE_ENDPOINT='https://your-proxmox:8006/'" >&2
  echo "  export PROXMOX_VE_API_TOKEN='user@realm!tokenid=secret'" >&2
  exit 1
fi

# Load .env. The file uses `export`, so sourcing is enough on its own; `set -a`
# also covers plain `KEY=value` lines.
set -a
# shellcheck disable=SC1090
. "./$ENV_FILE"
set +a

# Escape a value for an HCL double-quoted string. HCL also treats ${...} as
# interpolation, so that has to be escaped as well as \ and ".
hcl_escape() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//\$\{/\$\$\{}
  printf '%s' "$s"
}

as_bool() {
  case "${1:-}" in
    1 | true | TRUE | yes | on) printf 'true' ;;
    *) printf 'false' ;;
  esac
}

# Only the variables set in .env are written, so leaving one out means "fall
# back to the PROXMOX_VE_* environment variable", which the provider still does.
{
  echo "# GENERATED by tf.sh from .env — do not edit. Edit .env and re-run ./tf.sh"
  echo
  if [ -n "${PROXMOX_VE_ENDPOINT:-}" ]; then
    printf 'proxmox_endpoint  = "%s"\n' "$(hcl_escape "$PROXMOX_VE_ENDPOINT")"
  fi
  if [ -n "${PROXMOX_VE_API_TOKEN:-}" ]; then
    printf 'proxmox_api_token = "%s"\n' "$(hcl_escape "$PROXMOX_VE_API_TOKEN")"
  fi
  if [ -n "${PROXMOX_VE_INSECURE:-}" ]; then
    printf 'proxmox_insecure  = %s\n' "$(as_bool "$PROXMOX_VE_INSECURE")"
  fi

  # Any `TF_VAR_<name>` line in .env becomes `<name>` in the tfvars — the usual
  # Terraform env-var convention, so the line reads the way you would expect:
  #
  #   export TF_VAR_node_name='setup'
  #   export TF_VAR_disk_size='20'
  #
  # Numbers and booleans are unquoted so HCL does not treat them as strings.
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    key="${name#TF_VAR_}"
    value="${!name}"
    case "$value" in
      '' | *[!0-9.+-]*) printf '%s = "%s"\n' "$key" "$(hcl_escape "$value")" ;;
      *) printf '%s = %s\n' "$key" "$value" ;;
    esac
  done < <(compgen -v TF_VAR_)
} > "$TFVARS.tmp"

chmod 600 "$TFVARS.tmp"
mv "$TFVARS.tmp" "$TFVARS"

printf 'synced %s -> %s  (endpoint=%s, token=%s)\n' \
  "$ENV_FILE" "$TFVARS" \
  "${PROXMOX_VE_ENDPOINT:-<unset>}" \
  "$([ -n "${PROXMOX_VE_API_TOKEN:-}" ] && echo '<set>' || echo '<unset>')"

if [ "$#" -eq 0 ]; then
  echo "tfvars is ready. Now run: ./tf.sh plan  (then ./tf.sh apply)"
  exit 0
fi

exec terraform "$@"
